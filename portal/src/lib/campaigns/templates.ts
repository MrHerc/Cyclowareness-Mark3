export const TEMPLATE_BY_KEY = new Map(TEMPLATES.map((t) => [t.key, t]));

/** SMS and voice templates need the sms_voice feature, QR traps the qr_trap feature (checked on save and at every launch). */
export function templateOnPlan(tpl: CampaignTemplate, features: ReadonlySet<string>): boolean {
  if ((tpl.channel === "sms" || tpl.channel === "voice") && !features.has("sms_voice")) return false;
  return !tpl.qr || features.has("qr_trap");
}

export function templateText(value: L10n, locale: string): string {
  return value[locale as keyof L10n] ?? value.en;
}

